#!/usr/bin/env node
// Embeds packages/schema/migrations/*.sql into Sources/CaptureStore/Migrations.swift,
// so the daemon applies exactly the migrations the spec defines. Run after a migration
// is added or changed; CaptureStoreTests fails while the two differ.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'schema', 'migrations');
const names = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const body = names.map((name) => {
  const sql = readFileSync(join(dir, name), 'utf8');
  if (sql.includes('"""#')) throw new Error(`${name} cannot be embedded as a raw string`);
  return `        (name: "${name}", sql: #"""\n${sql}\n"""#),`;
}).join('\n');

writeFileSync(join(here, '..', 'Sources', 'CaptureStore', 'Migrations.swift'), `// Generated by scripts/embed-migrations.mjs from packages/schema/migrations. Do not edit.

enum Migrations {
    /// In order. A store records each by name in schema_migration, as the reference does,
    /// so either implementation can open a store the other made.
    static let all: [(name: String, sql: String)] = [
${body}
    ]
}
`);
console.log(`embedded ${names.length} migrations`);
